// Vendors the pure `@nest/plan` and `@nest/tax` sources into
// `supabase/functions/_shared/vendor/` so the edge functions can import them.
//
// The Supabase CLI bundles each edge function inside a container that sees only
// `supabase/functions/`, so an import that reaches `../../packages` fails the
// deploy ("failed to create the graph: Module not found"). The packages stay
// the single source of truth — this copies their `src/` verbatim (minus tests),
// stamps a "generated" header, and the `--check` mode fails CI when the copy has
// drifted from the source.
//
//   node scripts/vendor-edge-packages.js          # rewrite the vendored copy
//   node scripts/vendor-edge-packages.js --check  # assert it is in sync

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const REPO_ROOT = join(HERE, '..')
const PACKAGES = ['plan', 'tax']
const VENDOR_DIR = join(REPO_ROOT, 'supabase', 'functions', '_shared', 'vendor')

const HEADER =
  '// GENERATED by scripts/vendor-edge-packages.js — do not edit.\n' +
  '// Source of truth: packages/%PKG%/src/%FILE%. Run `pnpm vendor:edge` after\n' +
  '// changing the package, or CI (`pnpm check:vendor-edge`) will fail.\n\n'

/** Every non-test `.ts` file under a package's `src/`, relative to that `src/`. */
function sourceFiles(pkg) {
  const srcDir = join(REPO_ROOT, 'packages', pkg, 'src')
  return readdirSync(srcDir, { recursive: true })
    .filter((name) => name.endsWith('.ts') && !name.endsWith('.test.ts'))
    .sort()
}

/** The vendored content for one source file: the header plus the source verbatim. */
function vendoredContent(pkg, file) {
  const source = readFileSync(join(REPO_ROOT, 'packages', pkg, 'src', file), 'utf8')
  return HEADER.replace('%PKG%', pkg).replace('%FILE%', file) + source
}

const check = process.argv.includes('--check')
const drift = []

for (const pkg of PACKAGES) {
  const pkgVendorDir = join(VENDOR_DIR, pkg)
  const files = sourceFiles(pkg)

  if (!check) {
    rmSync(pkgVendorDir, { recursive: true, force: true })
  }

  for (const file of files) {
    const target = join(pkgVendorDir, file)
    const content = vendoredContent(pkg, file)
    if (check) {
      const current = existsSync(target) ? readFileSync(target, 'utf8') : null
      if (current !== content) {
        drift.push(relative(REPO_ROOT, target))
      }
    } else {
      mkdirSync(dirname(target), { recursive: true })
      writeFileSync(target, content)
    }
  }

  if (check) {
    const expected = new Set(files.map((file) => join(pkgVendorDir, file)))
    const actual = existsSync(pkgVendorDir)
      ? readdirSync(pkgVendorDir, { recursive: true })
          .filter((name) => name.endsWith('.ts'))
          .map((name) => join(pkgVendorDir, name))
      : []
    for (const path of actual) {
      if (!expected.has(path)) {
        drift.push(`${relative(REPO_ROOT, path)} (stale — no longer in the package)`)
      }
    }
  }
}

if (check) {
  if (drift.length > 0) {
    console.error(
      `The vendored edge copies are out of sync with packages/:\n  ${drift.join(
        '\n  ',
      )}\n\nRun \`pnpm vendor:edge\` and commit the result.`,
    )
    process.exit(1)
  }
  console.log('Vendored edge copies are in sync with packages/.')
} else {
  const total = PACKAGES.reduce((sum, pkg) => sum + sourceFiles(pkg).length, 0)
  console.log(`Vendored ${total} files into supabase/functions/_shared/vendor/.`)
}
